"""합성 점포 매출/부채 데이터 생성 (PoC용)"""
import numpy as np
import pandas as pd


def generate_synthetic_store(
    상권_코드: str,
    상권명: str,
    서비스_업종명: str,
    상권_평균_매출: float,
    seed: int = 42,
) -> dict:
    """
    상권 평균 매출 기반 합성 점포 데이터 생성.
    실제 금융 데이터 없이 PoC 시연용으로 사용.
    """
    rng = np.random.default_rng(seed)

    # 월 매출: 상권 평균의 70~130%
    월매출 = 상권_평균_매출 * rng.uniform(0.7, 1.3)

    # 고정비 구조 (매출의 60~75%)
    임대료 = 월매출 * rng.uniform(0.10, 0.20)
    인건비 = 월매출 * rng.uniform(0.25, 0.35)
    기타고정비 = 월매출 * rng.uniform(0.08, 0.15)
    변동비 = 월매출 * rng.uniform(0.20, 0.30)

    고정비 = 임대료 + 인건비 + 기타고정비
    총비용 = 고정비 + 변동비
    영업이익 = 월매출 - 총비용

    # 부채 구조 (금리는 % 단위 기준)
    대출잔액 = 월매출 * rng.uniform(6, 18)
    금리_pct = rng.uniform(4.0, 7.0)
    월이자 = 대출잔액 * (금리_pct / 100 / 12)
    현금보유 = 월매출 * rng.uniform(0.5, 3.0)

    # 최근 4분기 매출 추이 (합성)
    매출추이 = [
        월매출 * rng.uniform(0.85, 1.15)
        for _ in range(8)
    ]

    원금_상환_개월 = 60
    월_상환액 = 대출잔액 / 원금_상환_개월 + 월이자

    return {
        "상권_코드": 상권_코드,
        "상권명": 상권명,
        "업종": 서비스_업종명,
        "월_매출": round(월매출),
        "임대료": round(임대료),
        "월_임대료": round(임대료),
        "인건비": round(인건비),
        "월_인건비": round(인건비),
        "기타_고정비": round(기타고정비),
        "월_고정비": round(고정비),
        "변동비": round(변동비),
        "영업이익": round(영업이익),
        "대출잔액": round(대출잔액),
        "금리": round(금리_pct, 2),
        "월_이자": round(월이자),
        "월_상환액": round(월_상환액),
        "현금보유액": round(현금보유),
        "매출_추이_8분기": [round(v) for v in 매출추이],
    }


def calc_debt_resilience(store: dict) -> dict:
    """부채체력 진단 계산"""
    월매출 = store["월_매출"]
    월고정비 = store["월_고정비"]
    월이자 = store["월_이자"]
    현금 = store["현금보유액"]

    이자부담률 = (월이자 / 월매출 * 100) if 월매출 > 0 else 0
    고정비부담률 = (월고정비 / 월매출 * 100) if 월매출 > 0 else 0
    순현금흐름 = 월매출 - 월고정비 - 월이자 - store["변동비"]

    현금보유개월 = (현금 / abs(순현금흐름)) if 순현금흐름 < 0 else 999

    def 생존개월(감소율):
        감소후_매출 = 월매출 * (1 - 감소율)
        감소후_흐름 = 감소후_매출 - 월고정비 - 월이자 - store["변동비"] * (1 - 감소율* 0.5)
        if 감소후_흐름 >= 0:
            return 999
        return min(현금 / abs(감소후_흐름), 36)

    return {
        "이자부담률": round(이자부담률, 1),
        "고정비부담률": round(고정비부담률, 1),
        "현금보유개월": round(현금보유개월, 1) if 현금보유개월 < 999 else 999,
        "매출10감소_생존개월": round(생존개월(0.10), 1),
        "매출20감소_생존개월": round(생존개월(0.20), 1),
        "순현금흐름": round(순현금흐름),
    }
